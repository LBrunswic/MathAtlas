#!/usr/bin/env python3
"""The numbers of a status report, read off the repository and written as LaTeX macros.

    python3 tools/status_report.py OUTDIR [--logs DIR]

Writes OUTDIR/generated/numbers.tex (one \\newcommand per figure) and
OUTDIR/generated/closure-table.tex (one row per paper of the hub, plus GFN Bounds). Every number in
the report's prose is one of these macros, so a rerun refreshes the report and a hand-typed figure
has nowhere to hide.

Sources, all generated by the hub's own tools:
  * papers/<slug>/ledger/LEDGER.md and ledger.json  (tools/ledger.py) -- closure, buckets, findings
  * lean/docs/COVERAGE.md                            (GFNBoundsLean)  -- the GFN Bounds row
  * <pkg>/scripts/sorry_count.py                     (each package)  -- strict and scaffold sorrys
  * the `make -C <pkg> check` logs in --logs DIR (check-<pkg>.log)  -- the axiom-sweep counts.
    These need a Lean build, so they are read from logs and cached in generated/sweep.json;
    without --logs the cache is reused.
No model is called and no Lean is built here.
"""
import glob
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKAGES = {"lean-causal": "Causal", "lean-gx": "GX", "lean-benzecri": "Benzecri"}
# paper slug -> (title for the table, Lean home)
TITLES = {
    "barbot": ("Barbot, \\emph{GH flat space-times}", "lean-causal"),
    "ett": ("Brunswic, \\emph{Topological spacetimes (I)}", "lean-causal"),
    "gx": ("Brunswic, \\emph{Branched coverings of singular $(G,X)$-manifolds}", "lean-gx"),
    "benzecri": ("Benzécri, \\emph{Variétés localement affines \\dots}, Ch.~1", "lean-benzecri"),
    "egf": ("Brunswic et al., \\emph{Ergodic Generative Flows}", "---"),
    "syracuse": ("Brunswic, \\emph{Non-trivial cycles of $3x+1$}", "---"),
    "dyniso": ("\\emph{Orthogonal hyper-connections \\dots dynamical isometry}", "---"),
    "yamabe": ("Brunswic, \\emph{The Yamabe gap}", "---"),
    "nonacyclic": ("\\emph{Non-acyclic GFlowNets}", "---"),
    "bbs": ("Barbot--Bonsante--Schlenker, \\emph{Collisions I} (review)", "lean-gx"),
}


def macro_name(*parts):
    """\\numGxClosed from ('gx', 'closed'): letters only, each part capitalised."""
    out = "num"
    for p in parts:
        for w in re.split(r"[^A-Za-z]+", p):
            out += w[:1].upper() + w[1:]
    return out


def ledger_figures(slug):
    md = os.path.join(ROOT, "papers", slug, "ledger", "LEDGER.md")
    js = os.path.join(ROOT, "papers", slug, "ledger", "ledger.json")
    if not os.path.exists(md):
        return None
    text = open(md, encoding="utf-8").read()
    m = re.search(r"\*\*(\d+) statements\.\*\* Natural language: (\d+) proved or definitional\. "
                  r"Lean: \*\*(\d+) stated\*\*, of which \*\*(\d+) closed\*\* and (\d+) partial", text)
    c = re.search(r"\*\*Closure: (\d+) of (\d+)\.\*\*", text)
    assert m and c, "unrecognised ledger header in " + md
    f = {"statements": int(m[1]), "nlproved": int(m[2]), "stated": int(m[3]),
         "closedlean": int(m[4]), "partial": int(m[5]), "closed": int(c[1]), "target": int(c[2])}
    rows = json.load(open(js, encoding="utf-8"))["statements"]
    f["terminal"] = sum(1 for r in rows if r.get("bucket") == "T")
    f["findings"] = sum(len(r.get("paper_findings") or []) for r in rows)
    f["findingrows"] = sum(1 for r in rows if r.get("paper_findings"))
    return f


def gfn_figures():
    cov = os.path.join(ROOT, "lean", "docs", "COVERAGE.md")
    text = open(cov, encoding="utf-8").read()
    m = re.search(r"\*\*(\d+) closed · (\d+) partial · (\d+) open · (\d+) stale\*\*, of (\d+) statements", text)
    assert m, "unrecognised COVERAGE.md header"
    return {"closed": int(m[1]), "partial": int(m[2]), "open": int(m[3]), "statements": int(m[5])}


def package_figures(pkg, sweep):
    d = os.path.join(ROOT, pkg)
    lib = PACKAGES[pkg]
    files = glob.glob(os.path.join(d, lib, "**", "*.lean"), recursive=True)
    lines = sum(sum(1 for _ in open(f, encoding="utf-8")) for f in files)
    out = subprocess.run([sys.executable, os.path.join(d, "scripts", "sorry_count.py")], cwd=d,
                         capture_output=True, text=True)
    strict = re.search(r"sorry \(strict[^:]*:\s*(\d+)", out.stdout)
    scaff = re.search(r"sorry \(scaffold[^:]*:\s*(\d+)", out.stdout)
    assert strict and scaff, "unrecognised sorry_count output in " + pkg + ": " + out.stdout[-300:]
    f = {"files": len(files), "lines": lines, "sorrystrict": int(strict[1]),
         "sorryscaffold": int(scaff[1])}
    f.update(sweep.get(pkg, {}))
    return f


def read_sweeps(logdir, cache):
    sweep = json.load(open(cache)) if os.path.exists(cache) else {}
    if logdir:
        for pkg in PACKAGES:
            log = os.path.join(logdir, "check-%s.log" % pkg)
            text = open(log, encoding="utf-8").read()
            m = re.search(r"axiom sweep \(strict\): (\d+) declarations in (\d+) modules", text)
            ok = re.search(r"axiom sweep: all within propext/Classical\.choice/Quot\.sound", text)
            assert m and ok, "no clean axiom sweep in " + log
            sweep[pkg] = {"decls": int(m[1]), "modules": int(m[2])}
    assert set(sweep) == set(PACKAGES), "axiom-sweep counts missing: pass --logs once"
    return sweep


def fmt(n):
    return "{:,}".format(n).replace(",", "\\,") if isinstance(n, int) else n


def main(argv):
    if not argv or argv[0].startswith("-"):
        sys.exit(__doc__)
    outdir = os.path.join(argv[0], "generated")
    logdir = argv[argv.index("--logs") + 1] if "--logs" in argv else None
    os.makedirs(outdir, exist_ok=True)
    cache = os.path.join(outdir, "sweep.json")
    sweep = read_sweeps(logdir, cache)
    with open(cache, "w") as fh:
        json.dump(sweep, fh, indent=2, sort_keys=True)
        fh.write("\n")

    macros = {}
    table = []
    for slug in TITLES:
        f = ledger_figures(slug)
        title, home = TITLES[slug]
        if f is None:
            table.append("%s & \\texttt{%s} & \\multicolumn{5}{l}{no ledger} \\\\" % (title, home))
            continue
        for k, v in f.items():
            macros[macro_name(slug, k)] = v
        table.append("%s & \\texttt{%s} & %d & %d & %d & %d & \\textbf{%d/%d} \\\\" % (
            title, home, f["statements"], f["terminal"], f["stated"], f["partial"], f["closed"], f["target"]))
    g = gfn_figures()
    for k, v in g.items():
        macros[macro_name("gfn", k)] = v
    table.append("Brunswic et al., \\emph{GFN Bounds}, App.~A, B, H & \\texttt{lean} & %d & %d & %d & %d & \\textbf{%d/%d} \\\\"
                 % (g["statements"], g["open"], g["closed"] + g["partial"], g["partial"],
                    g["closed"], g["statements"] - g["open"]))
    for pkg in PACKAGES:
        for k, v in package_figures(pkg, sweep).items():
            macros[macro_name(pkg.replace("lean-", "pkg-"), k)] = v

    with open(os.path.join(outdir, "numbers.tex"), "w", encoding="utf-8") as fh:
        fh.write("% generated by tools/status_report.py -- do not edit\n")
        for k in sorted(macros):
            fh.write("\\newcommand{\\%s}{%s}\n" % (k, fmt(macros[k])))
    with open(os.path.join(outdir, "closure-table.tex"), "w", encoding="utf-8") as fh:
        fh.write("% generated by tools/status_report.py -- do not edit\n")
        fh.write("\n".join(table) + "\n")
    print("status_report: %d macros, %d table rows -> %s" % (len(macros), len(table), outdir))


if __name__ == "__main__":
    main(sys.argv[1:])
