"""T-abs-hoist-dual-cover: emit-lean and the DualTest generator in memory, never in place (kb/0252).

    git archive HEAD lean-causal/Causal lean-causal/Causal.lean | tar -x -C /tmp/hdc/headsrc
    git show HEAD:programme/ladder.toml > /tmp/hdc/ladder_HEAD.toml
    python3 -I emit_probe.py

Rules.lean and Test.lean are emitted from HEAD's ladder.toml with HEAD's sources and with the
working tree's, and compared with each other and with the files on disk. DualTest is generated by
campaign/T-tac-ladder-dual/dual_closure.py into /tmp only.
"""
import runpy
import sys

REPO = "/home/maxbrain/Dropbox/LeanArticles"
sys.path.insert(0, REPO + "/tools")
import ladder  # noqa: E402

HEAD_SRC, HEAD_TOML = "/tmp/hdc/headsrc/lean-causal", "/tmp/hdc/ladder_HEAD.toml"
data = ladder.load(HEAD_TOML)
disk = {n: open(f"{REPO}/lean-causal/Causal/Ladder/{n}.lean", encoding="utf-8").read()
        for n in ("Rules", "Test", "DualTest")}
for tag, root in (("head", HEAD_SRC), ("now", REPO + "/lean-causal")):
    idx = ladder._lean_index(root)
    print(tag, "Rules == on-disk:", ladder.emit_lean(data, idx) == disk["Rules"],
          "; Test == on-disk:", ladder.emit_test(data, idx) == disk["Test"])
_load, _idx = ladder.load, ladder.lean_index
ladder.load = lambda *a, **k: _load(HEAD_TOML)
for tag, root in (("head", HEAD_SRC), ("now", REPO + "/lean-causal")):
    ladder.lean_index = lambda *a, root=root, **k: _idx(root)
    out = f"/tmp/hdc/DT_{tag}.lean"
    sys.argv = ["dual_closure.py", "shipped", out]
    runpy.run_path(REPO + "/lean-causal/campaign/T-tac-ladder-dual/dual_closure.py", run_name="__main__")
    print(tag, "DualTest == on-disk:", open(out, encoding="utf-8").read() == disk["DualTest"])
