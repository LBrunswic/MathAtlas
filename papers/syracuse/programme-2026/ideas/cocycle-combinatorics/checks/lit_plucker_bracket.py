#!/usr/bin/env python3
r"""R3 (Plucker / bracket algebra) verification for cocycle-combinatorics.

Reads Huang-Perlman-Polini-Raicu-Sammartano, *Relations between the 2x2 minors
of a generic matrix* (arXiv:1909.11705), against STRUCTURE.md sec.3/sec.5.

Two linked questions:

  Q1  Is C8 the COMPLETE generating relation of the core ideal E0 = I_2 over
      Z[X,Y]?  C8 (our notation) is the Grassmann-Plucker / Eagon-Northcott /
      Lascoux FIRST SYZYGY of I_2:  sum_cyc D(u) C(v,w) = 0.  The paper (sec.7,
      p.20) calls Syz(I_2) "solved by Lascoux"; for a *generic* 2 x n matrix
      that module is generated by the Plucker PAIR (a D-row AND an S-row three-
      term syzygy per triple), with Koszul redundant.  Does that transfer to our
      NON-generic state matrix (2 rows (D,S), 2n entries that are cocycle
      polynomials in just X,Y)?

  Q2  The difference ideal J = <S^(i) - S^(j)> = the zero-sum / augmentation
      ideal of the rotation sums (approaches/zero-sum-combination).  Principal
      over Z[1/6] (gcd of differences).  Is it a FINER, o-independent ceiling
      than a single core / than G = gcd_j S^(j) = |D| on a cycle, or does it
      collapse to the rotation-combo floor?

Method validated against a genuinely generic 2 x n matrix (PART B): for that the
Plucker pair generates Syz and Koszul is redundant -- exactly Eagon-Northcott /
Lascoux -- so any failure of that on our matrix (PART C) is a real specialization
syzygy, not a tooling artefact.

Robust: every algebraic identity is checked symbolically; syzygy modules use
sympy's agca over QQ[X,Y].  Exit 0 iff every asserted check passes.
"""
from __future__ import annotations

import sys
import os
from math import gcd
from functools import reduce

import sympy as sp
from sympy import QQ

sys.path.insert(
    0,
    os.path.join(os.path.dirname(__file__), "..", "..", "..",
                 "approaches", "cocycle-combine", "lib"),
)
from cocycle import S, D, core_C, rotations, X, Y  # noqa: E402

R = QQ.old_poly_ring(X, Y)
PASS, FAIL = [], []


def check(name, cond):
    (PASS if cond else FAIL).append(name)
    print(("  [ok] " if cond else "  [XX] ") + name)
    return cond


# --------------------------------------------------------------------------- #
# helpers                                                                     #
# --------------------------------------------------------------------------- #
def cores_of(cols):
    n = len(cols)
    idx = [(i, j) for i in range(n) for j in range(i + 1, n)]
    cs = [sp.expand(core_C(cols[i], cols[j])) for (i, j) in idx]
    return cs, idx


def plucker_vectors(cols, idx, row):
    """The three-term Plucker / Eagon-Northcott syzygies for one matrix row.

    row='D':  sum_cyc D(w_i) C(w_j,w_k) = 0   (== STRUCTURE.md C8)
    row='S':  sum_cyc S(w_i) C(w_j,w_k) = 0   (the S-row companion)
    one vector per triple i<j<k, as a coefficient tuple over the cores `idx`.
    """
    n = len(cols)
    pos = {p: k for k, p in enumerate(idx)}
    f = (lambda w: sp.expand(D(w))) if row == "D" else (lambda w: sp.expand(S(w)))

    def loc(a, b):
        s = 1
        if a > b:
            a, b, s = b, a, -1
        return pos[(a, b)], s

    out = []
    for i in range(n):
        for j in range(i + 1, n):
            for k in range(j + 1, n):
                v = [sp.Integer(0)] * len(idx)
                p, s = loc(j, k); v[p] += s * f(cols[i])
                p, s = loc(i, k); v[p] += -s * f(cols[j])
                p, s = loc(i, j); v[p] += s * f(cols[k])
                out.append(v)
    return out


def koszul_vectors(cores):
    """Trivial syzygies  C_b * e_a - C_a * e_b."""
    N = len(cores)
    out = []
    for a in range(N):
        for b in range(a + 1, N):
            v = [sp.Integer(0)] * N
            v[a] = cores[b]; v[b] = -cores[a]
            out.append(v)
    return out


def submod(vecs, N):
    return R.free_module(N).submodule(*[list(v) for v in vecs])


def syz_of_cores(cores):
    return R.free_module(1).submodule(*[[c] for c in cores]).syzygy_module()


def modules_equal(A, B):
    return A.is_submodule(B) and B.is_submodule(A)


def sixfree(n):
    n = abs(int(n))
    if n == 0:
        return 0
    for p in (2, 3):
        while n % p == 0:
            n //= p
    return n


def gall(xs):
    xs = [abs(int(x)) for x in xs if x != 0]
    return reduce(gcd, xs) if xs else 0


# --------------------------------------------------------------------------- #
print("=" * 72)
print("PART A -- Plucker identities (both rows) are genuine syzygies of I_2")
print("=" * 72)
# antisymmetry + the two three-term Plucker syzygies are polynomial identities.
for (u, v) in [((1, 2), (3,)), ((2, 1, 1), (1, 3)), ((1,), (2, 2, 1))]:
    check(f"antisymmetry C(u,v)=-C(v,u)  u={u} v={v}",
          sp.expand(core_C(u, v) + core_C(v, u)) == 0)

for w in [(1, 2, 3), (2, 1, 1, 3)]:
    cols = rotations(w)
    cores, idx = cores_of(cols)
    for row in ("D", "S"):
        ok = all(
            sp.expand(sum(v[k] * cores[k] for k in range(len(cores)))) == 0
            for v in plucker_vectors(cols, idx, row)
        )
        check(f"{row}-row three-term Plucker syzygy == 0   w={w}", ok)
print("  -> STRUCTURE.md states only the D-row (C8); the S-row companion"
      "\n     sum_cyc S(u)C(v,w)=0 is an equally genuine generic syzygy.")

# --------------------------------------------------------------------------- #
print("=" * 72)
print("PART B -- CONTROL: generic 2 x n matrix, Syz(I_2) = <Plucker pair>")
print("        (validates method; reproduces Eagon-Northcott / Lascoux)")
print("=" * 72)
for n in (3, 4):
    a = sp.symbols(f"a0:{n}"); b = sp.symbols(f"b0:{n}")
    Rg = QQ.old_poly_ring(*(list(a) + list(b)))
    idx = [(i, j) for i in range(n) for j in range(i + 1, n)]
    pos = {p: k for k, p in enumerate(idx)}
    cores = [sp.expand(a[i] * b[j] - a[j] * b[i]) for (i, j) in idx]
    N = len(cores)

    def gplu(row):
        f = a if row == "a" else b
        out = []
        for i in range(n):
            for j in range(i + 1, n):
                for k in range(j + 1, n):
                    v = [sp.Integer(0)] * N
                    v[pos[(j, k)]] += f[i]
                    v[pos[(i, k)]] += -f[j]
                    v[pos[(i, j)]] += f[k]
                    out.append(v)
        return out

    def gkos():
        out = []
        for x in range(N):
            for y in range(x + 1, N):
                v = [sp.Integer(0)] * N
                v[x] = cores[y]; v[y] = -cores[x]
                out.append(v)
        return out

    Syz = Rg.free_module(1).submodule(*[[c] for c in cores]).syzygy_module()
    FN = Rg.free_module(N)
    Plu = FN.submodule(*[list(v) for v in gplu("a") + gplu("b")])
    PluK = FN.submodule(*[list(v) for v in gplu("a") + gplu("b") + gkos()])
    Pa = FN.submodule(*[list(v) for v in gplu("a") + gkos()])
    check(f"generic n={n}: Syz == <Plucker pair (a-row,b-row)>",
          Syz.is_submodule(Plu) and Plu.is_submodule(Syz))
    check(f"generic n={n}: Koszul redundant (in <Plucker pair>)",
          Plu.is_submodule(PluK) and PluK.is_submodule(Plu))
    check(f"generic n={n}: ONE row's Plucker + Koszul is NOT enough "
          "(both rows needed)",
          not (Syz.is_submodule(Pa) and Pa.is_submodule(Syz)))

# --------------------------------------------------------------------------- #
print("=" * 72)
print("PART C -- Q1: on OUR non-generic state matrix C8 is NOT complete")
print("=" * 72)

print("-- cycle/rotation stratum (rotations share a constant D-row):")
for w in [(1, 2, 1), (1, 2, 3), (2, 1, 1, 3)]:
    cols = rotations(w)
    cores, idx = cores_of(cols)
    N = len(cores)
    pos = {p: k for k, p in enumerate(idx)}
    # constant-coefficient telescoping syzygy over triple (0,1,2)
    tele = [sp.Integer(0)] * N
    tele[pos[(1, 2)]] = 1; tele[pos[(0, 2)]] = -1; tele[pos[(0, 1)]] = 1
    Dv = sp.expand(D(cols[0]))
    c8D = plucker_vectors(cols, idx, "D")[0]   # triple (0,1,2)
    check(f"w={w}: C8(D-row) == D * telescoping  (C8 non-minimal here)",
          all(sp.expand(c8D[k] - Dv * tele[k]) == 0 for k in range(N)))
    check(f"w={w}: telescoping sum_cyc C = 0 is a genuine syzygy",
          sp.expand(sum(tele[k] * cores[k] for k in range(N))) == 0)
    PluK = submod(plucker_vectors(cols, idx, "D")
                  + plucker_vectors(cols, idx, "S")
                  + koszul_vectors(cores), N)
    check(f"w={w}: telescoping NOT in <Plucker pair, Koszul> (a FINER relation)",
          not PluK.contains(tele))
    Syz = syz_of_cores(cores)
    check(f"w={w}: Syz STRICTLY bigger than <Plucker pair, Koszul>",
          Syz.is_submodule(PluK) is False or not modules_equal(Syz, PluK))

print("-- distinct words, distinct D (still non-generic: entries in Z[X,Y]):")
for cols in [[(1,), (2,), (1, 2), (2, 1, 1)],
             [(1,), (1, 2), (2, 1, 1)]]:
    cores, idx = cores_of(cols)
    N = len(cores)
    PluK = submod(plucker_vectors(cols, idx, "D")
                  + plucker_vectors(cols, idx, "S")
                  + koszul_vectors(cores), N)
    Syz = syz_of_cores(cores)
    check(f"cols={cols}: Syz != <Plucker pair, Koszul> (C8 incomplete)",
          not modules_equal(Syz, PluK))

# --------------------------------------------------------------------------- #
print("=" * 72)
print("PART D -- Q2: difference ideal J at (2,3) = zero-sum ideal; collapses")
print("           to the rotation-combo floor G (never finer as a ceiling)")
print("=" * 72)
battery = [(1, 2, 1), (1, 1, 2, 3), (2, 1, 3, 1), (1, 2, 1, 3, 2),
           (3, 1, 1, 2), (2, 2, 1, 1, 3), (1, 3, 2, 1, 2, 1)]
all_GdivD = all_DgeG = all_split = all_finer = all_sf = True
for w in battery:
    rots = rotations(w)
    Sv = [int(S(r, 2, 3)) for r in rots]
    diffs = [Sv[i] - Sv[j] for i in range(len(rots))
             for j in range(i + 1, len(rots)) if Sv[i] != Sv[j]]
    G = gall(Sv)                       # = |D| on a genuine cycle
    Delta = gall(diffs)                # generator of J at (2,3)
    minsd = min(abs(d) for d in diffs)
    all_GdivD &= (Delta % G == 0)                       # G | Delta
    all_DgeG &= (Delta >= G)                            # floor
    all_split &= (gcd(abs(Sv[0]), Delta) == G)          # G = gcd(S0, diff-gcd)
    all_finer &= (Delta < minsd)                        # ideal finer than single
    all_sf &= (sixfree(Delta) % G == 0)                 # sixfree still >= G
check("J=zero-sum ideal: G = gcd(S^(0), gcd-of-differences)   (general-theory)",
      all_split)
check("J finer than any single difference: gcd(diffs) < min|single diff|",
      all_finer)
check("COLLAPSE: G | gcd(diffs), so gen(J) >= G (rotation-combo floor)",
      all_GdivD and all_DgeG)
check("COLLAPSE: sixfree(gen(J)) is a multiple of G -> >= G on the floor too",
      all_sf)

# --------------------------------------------------------------------------- #
print("=" * 72)
print("PART E -- Q2: the FINER polynomial gcd X^a(X-1) is a DIVISOR of every")
print("           difference but (non-PID) NOT a member of J -> not realizable")
print("=" * 72)
for w in [(1, 2, 1), (1, 1, 2, 3), (2, 1, 3)]:
    rots = rotations(w)
    Sv = [sp.expand(S(r)) for r in rots]
    ds = [sp.expand(Sv[i] - Sv[j]) for i in range(len(rots))
          for j in range(i + 1, len(rots))]
    ds = [d for d in ds if d != 0]
    g = ds[0]
    for d in ds[1:]:
        g = sp.gcd(g, d)
    g = sp.expand(g)
    Jp = R.free_module(1).submodule(*[[d] for d in ds])
    check(f"w={w}: polyGCD(diffs) = {sp.factor(g)}  divides every difference",
          all(sp.rem(d, g, X) == 0 or sp.simplify(sp.cancel(d / g)).is_polynomial()
              for d in ds))
    check(f"w={w}: that gcd is NOT in the ideal J=<diffs> over QQ[X,Y] "
          "(non-PID; not a realizable zero-sum core)",
          not Jp.contains([g]))

# --------------------------------------------------------------------------- #
print("=" * 72)
print(f"SUMMARY: {len(PASS)} passed, {len(FAIL)} failed")
if FAIL:
    for f in FAIL:
        print("  FAILED:", f)
    sys.exit(1)
print("ALL CHECKS PASSED")
sys.exit(0)
